  // 기분에 따른 고양이 울음소리 반환
  getCatSound(emotion) {
    const sounds = this.catSounds[emotion] || this.catSounds.happy;
    const randomSound = sounds[Math.floor(Math.random() * sounds.length)];
    // 길게 울음 (반복)
    return randomSound + ' ' + randomSound;
  }

  // 성격과 감정에 따른 응답 반환
  getResponse(personality, emotion) {
    const personalityResponses = this.responses.ko[personality];
    if (!personalityResponses) return '뭐하는 거야?';

    const emotionResponses = personalityResponses[emotion] || personalityResponses.happy;
    if (!emotionResponses || emotionResponses.length === 0) return '뭐하는 거야?';

    return emotionResponses[Math.floor(Math.random() * emotionResponses.length)];
  }

  // 고양이가 아닌 사진에 대한 화난 응답
  getNonCatResponse(personality) {
    const angryResponses = this.responses.ko[personality]?.angry || ['뭐야?'];
    const baseResponse = angryResponses[Math.floor(Math.random() * angryResponses.length)];

    return `어? 이게 뭐야?! 고양이가 아니네!! 뭐하는 거야?! 내 사진을 올려! 이건 뭔 동물이야?! 정말 화난다!! 내 시간 낭비하지 말고 고양이 사진을 올려!!`;
  }

  // 완전한 고양이 응답 생성 (울음소리 + 텍스트)
  generateFullResponse(personality, emotion) {
    const catSound = this.getCatSound(emotion);
    const response = this.getResponse(personality, emotion);
    return `${catSound}\n\n${response}`;
  }

  // 고양이가 아닌 사진 응답
  generateNonCatResponse(personality) {
    const catSound = this.getCatSound('angry');
    const response = this.getNonCatResponse(personality);
    return `${catSound}\n\n${response}`;
  }
